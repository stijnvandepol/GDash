#!/usr/bin/env bash
# Writes THIRD_PARTY_LICENSES: the license texts of every Go module compiled
# into the daycast binary and every npm package bundled into its web
# interface. Their licenses (MIT, BSD) ask that these notices travel with the
# program. Needs the Go modules and web/node_modules installed.
#
# CI runs this and fails when the committed file differs, so a new
# dependency cannot ship without its notice.
set -euo pipefail
export LC_ALL=C
cd "$(dirname "$0")/.."

# license_files prints the license-like files at the root of a package.
license_files() {
  find "$1" -maxdepth 1 -type f \( -iname 'LICEN[CS]E*' -o -iname 'COPYING*' -o -iname 'NOTICE*' -o -iname 'PATENTS*' \) | sort
}

# section prints one package's heading and license texts.
section() {
  local name=$1 dir=$2 files
  files=$(license_files "$dir")
  if [ -z "$files" ]; then
    echo "no license file found for $name in $dir" >&2
    exit 1
  fi
  printf '%s\n%s\n\n' "================================================================================" "$name"
  while IFS= read -r file; do
    # Strip carriage returns, so the output is the same on every OS.
    tr -d '\r' < "$file"
    printf '\n'
  done <<< "$files"
}

{
  printf 'Daycast includes the third-party software listed below, under the\n'
  printf 'licenses that follow each name. Generated by scripts/third-party-licenses.sh.\n\n'

  # The modules differ per operating system, so take those of every release
  # target; the file is then the same whichever machine writes it.
  for target in linux/amd64 linux/arm64 linux/arm windows/amd64; do
    GOOS=${target%/*} GOARCH=${target#*/} go list -deps \
      -f '{{if .Module}}{{if not .Module.Main}}{{.Module.Path}}@{{.Module.Version}} {{.Module.Dir}}{{end}}{{end}}' ./cmd/daycast
  done |
    sort -u |
    while read -r module dir; do
      section "$module (Go)" "$dir"
    done

  node web/scripts/bundled-packages.mjs | tr -d '\r' | while read -r package; do
    version=$(node -p "require('./web/node_modules/$package/package.json').version" | tr -d '\r')
    section "$package@$version (npm)" "web/node_modules/$package"
  done
} > THIRD_PARTY_LICENSES
